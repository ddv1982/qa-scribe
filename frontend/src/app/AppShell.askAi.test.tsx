import '@testing-library/jest-dom/vitest'
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, expect, it } from 'vitest'
import { AppShell } from './AppShell'
import { draftFixture, findingFixture } from '../test/fixtures'
import { cleanupControllerTest, getTauriMock, setupControllerTest, renderWithControllerStartup, useAppController } from './useAppController.testHarness'

const api = getTauriMock()
function Subject() { return <AppShell {...useAppController()} /> }
beforeEach(() => { setupControllerTest(); api.listFindings.mockResolvedValue([findingFixture()]) })
afterEach(cleanupControllerTest)

it.each(['manual finding', 'generated finding', 'manual test case', 'generated test case'])('opens a fresh %s composer while preserving literal Notes input', async label => {
  const testCase = label.includes('test case')
  api.listDrafts.mockResolvedValue([draftFixture({ aiRunId: label.startsWith('generated') ? 'synthetic-run' : null })])
  await renderWithControllerStartup(() => render(<Subject />))
  fireEvent.click(screen.getByRole('button', { name: 'Chat' }))
  const notes = await screen.findByRole('textbox', { name: 'Message' })
  fireEvent.change(notes, { target: { value: 'Notes input stays in Notes. 雪 4827.' } })
  fireEvent.click(screen.getByRole('tab', { name: testCase ? /Test cases/ : /Findings/ }))
  fireEvent.click(await screen.findByRole('button', { name: 'Ask AI' }))
  const input = await screen.findByRole('textbox', { name: 'Message' })
  await waitFor(() => expect(input).toBeEnabled())
  expect(input).toHaveValue('')
  expect(input).not.toBe(notes)
  expect(input).toHaveFocus()
  expect(screen.getByRole('region', { name: 'Chat source' })).toHaveTextContent(testCase ? 'Checkout test cases' : 'Checkout returns 500')
  const panel = screen.getByRole('complementary', { name: 'Ask AI' })
  expect(within(panel).queryByRole('heading', { name: 'Conversation' })).not.toBeInTheDocument()
  expect(within(panel).queryByText(/shared Session/)).not.toBeInTheDocument()
  expect(within(panel).queryByRole('button', { name: 'Add conversation to Note' })).not.toBeInTheDocument()
  expect(within(panel).queryByRole('button', { name: 'Start new conversation' })).not.toBeInTheDocument()
  expect(within(panel).queryByRole('button', { name: 'Detach record context' })).not.toBeInTheDocument()
  expect(api.startChatJob).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Close Ask AI' }))
  fireEvent.click(screen.getByRole('tab', { name: 'Note' }))
  fireEvent.click(await screen.findByRole('button', { name: 'Chat' }))
  expect(await screen.findByRole('textbox', { name: 'Message' })).toBe(notes)
  expect(notes).toHaveValue('Notes input stays in Notes. 雪 4827.')
})

it('reclick focuses occupied input and settled Close reopens fresh', async () => {
  await renderWithControllerStartup(() => render(<Subject />))
  fireEvent.click(screen.getByRole('tab', { name: /Findings/ }))
  fireEvent.click(await screen.findByRole('button', { name: 'Ask AI' }))
  const input = await screen.findByRole('textbox', { name: 'Message' })
  await waitFor(() => expect(input).toBeEnabled())
  fireEvent.change(input, { target: { value: 'Unsent tester question' } })
  fireEvent.click(screen.getByRole('button', { name: 'Ask AI' }))
  expect(screen.getByRole('textbox', { name: 'Message' })).toBe(input)
  expect(input).toHaveValue('Unsent tester question')
  expect(input).toHaveFocus()
  fireEvent.click(screen.getByRole('button', { name: 'Close Ask AI' }))
  await waitFor(() => expect(screen.queryByRole('complementary', { name: 'Ask AI' })).not.toBeInTheDocument())
  fireEvent.click(screen.getByRole('button', { name: 'Ask AI' }))
  await waitFor(() => expect(screen.getByRole('textbox', { name: 'Message' })).toHaveValue(''))
  expect(screen.getByRole('textbox', { name: 'Message' })).not.toBe(input)
  expect(screen.getByRole('heading', { name: 'Improve this finding' })).toBeInTheDocument()
  expect(screen.getByText('You can also ask to add it to Jira.')).toBeInTheDocument()
  expect(api.saveChatComposer).toHaveBeenCalledWith(expect.objectContaining({ composer: 'Unsent tester question' }))
  expect(api.updateFinding).not.toHaveBeenCalled()
})

it('keeps unsaved source edits while the ordinary composer stays empty', async () => {
  await renderWithControllerStartup(() => render(<Subject />))
  fireEvent.click(screen.getByRole('tab', { name: /Findings/ }))
  await screen.findByRole('button', { name: 'Ask AI' })
  fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
  fireEvent.change(screen.getByRole('textbox', { name: 'Finding title' }), { target: { value: 'Unsaved checkout title' } })
  fireEvent.click(screen.getByRole('button', { name: 'Ask AI' }))
  await waitFor(() => expect(screen.getByRole('region', { name: 'Chat source' })).toHaveTextContent('Unsaved checkout title'))
  expect(screen.getByRole('textbox', { name: 'Message' })).toHaveValue('')
  expect(screen.getByRole('textbox', { name: 'Finding title' })).toHaveValue('Unsaved checkout title')
  expect(api.updateFinding).not.toHaveBeenCalled()
  expect(api.startChatJob).not.toHaveBeenCalled()
})
