it('keeps authored rich text and images until Apply format and retains finding details', async () => {
  render(<Workspace />)
  const create = await screen.findByRole('button', { name: 'Create finding' })
  await waitFor(() => expect(create).toBeEnabled())
  fireEvent.click(create)
  const template = await screen.findByRole('combobox', { name: 'Finding template' })
  const body = screen.getByRole('textbox', { name: 'Creation draft body' })
  const title = screen.getByRole('textbox', { name: 'Finding title' })
  fireEvent.change(title, { target: { value: 'Keep details' } })
  fireEvent.change(screen.getByRole('combobox', { name: 'Finding type' }), { target: { value: 'risk' } })
  fireEvent.change(screen.getByRole('combobox', { name: 'Severity' }), { target: { value: 'high' } })
  fireEvent.change(screen.getByRole('combobox', { name: 'Status' }), { target: { value: 'resolved' } })
  const labels = Array.from(document.querySelectorAll('.creation-fields label > span'), span => span.textContent)
  expect(labels.slice(0, 4)).toEqual(['Finding type', 'Severity', 'Status', 'Template'])
  body.focus()
  fireEvent.paste(body, { clipboardData: { files: [], items: [], types: ['text/html'], getData: (type: string) => type === 'text/html' ? '<p><strong>Keep authored body</strong></p><img src="qa-scribe-attachment://note-evidence" data-attachment-id="note-evidence" alt="Evidence">' : '' } })
  await waitFor(() => expect(body.querySelector('img')).toHaveAttribute('data-attachment-id', 'note-evidence'))
  const originalHtml = body.innerHTML
  fireEvent.change(template, { target: { value: 'blank' } })
  const dialog = screen.getByRole('dialog', { name: 'Replace the draft structure?' })
  expect(template).toHaveValue('structured')
  fireEvent.click(within(dialog).getByRole('button', { name: 'Keep editing' }))
  expect(body.innerHTML).toBe(originalHtml)
  fireEvent.change(template, { target: { value: 'blank' } })
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Apply format' }))
  expect(template).toHaveValue('blank')
  expect(body).toHaveTextContent('')
  expect(body.querySelector('img')).toBeNull()
  expect(title).toHaveValue('Keep details')
  expect(screen.getByRole('combobox', { name: 'Finding type' })).toHaveValue('risk')
  expect(screen.getByRole('combobox', { name: 'Severity' })).toHaveValue('high')
  expect(screen.getByRole('combobox', { name: 'Status' })).toHaveValue('resolved')
  fireEvent.click(screen.getByRole('button', { name: 'Save finding' }))
  await waitFor(() => expect(tauri.commitCreationSave).toHaveBeenCalledOnce())
  const payload = tauri.commitCreationSave.mock.calls[0][0] as import('../tauri').CommitCreationSave
  expect(payload.record).toMatchObject({ kind: 'finding', title: 'Keep details', findingKind: 'risk', body: '' })
  expect(JSON.parse(payload.record.metadataJson!)).toEqual({ severity: 'high', status: 'resolved', manualCreationFormat: { version: 1, format: { kind: 'finding', template: 'blank' } } })
})
