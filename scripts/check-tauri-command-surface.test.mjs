import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'

const checker = fileURLToPath(new URL('./check-tauri-command-surface.mjs', import.meta.url))
const ordinary = 'commands::chat::get_chat,'
const composer = 'commands::chat::save_chat_composer::<tauri::Wry>,'

function check(registrations, responseType = 'ChatState') {
  const root = mkdtempSync(join(tmpdir(), 'qa-command-surface-'))
  const write = (name, content) => {
    const path = join(root, name)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content)
  }
  try {
    write('src-tauri/build.rs', 'const COMMANDS: &[&str] = &["get_chat", "save_chat_composer"];')
    write('src-tauri/src/specta_bindings.rs', `.commands(collect_commands![${registrations.join('\n')}])`)
    write('frontend/src/bindings.ts', `__TAURI_INVOKE<${responseType}>("get_chat");\n__TAURI_INVOKE<${responseType}>("save_chat_composer");`)
    write('src-tauri/permissions/default.toml', 'permissions = ["allow-get-chat", "allow-save-chat-composer"]')
    write('src-tauri/permissions/autogenerated/get_chat.toml', '')
    write('src-tauri/permissions/autogenerated/save_chat_composer.toml', '')
    write('src-tauri/capabilities/default.json', JSON.stringify({
      windows: ['main'],
      permissions: ['core:event:allow-listen', 'core:event:allow-unlisten', 'core:window:allow-destroy', 'default'],
    }))
    return spawnSync(process.execPath, [checker], { cwd: root, encoding: 'utf8' })
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
}

test('ordinary and explicit Wry Specta registrations preserve the command census', () => {
  for (const registration of [composer, 'commands::chat::save_chat_composer,']) {
    const result = check([ordinary, registration])
    assert.equal(result.status, 0, result.stderr)
    assert.match(result.stdout, /OK.*2 commands/)
  }
})

test('a missing ordinary or Wry registration still fails', () => {
  for (const registrations of [[ordinary], [composer]]) {
    const result = check(registrations)
    assert.equal(result.status, 1)
    assert.match(result.stderr, /Specta handler differs from build manifest/)
    assert.match(result.stderr, /missing: (?:get_chat|save_chat_composer)/)
  }
})

test('duplicate Wry registrations still fail', () => {
  const result = check([ordinary, composer, composer])
  assert.equal(result.status, 1)
  assert.match(result.stderr, /Specta handler contains duplicate commands/)
})

test('unregistered ordinary and Wry commands still fail', () => {
  for (const registration of ['commands::chat::unknown,', 'commands::chat::unknown::<tauri::Wry>,']) {
    const result = check([ordinary, composer, registration])
    assert.equal(result.status, 1)
    assert.match(result.stderr, /extra: unknown/)
  }
})

test('unsupported and malformed generic syntax cannot hide a missing command', () => {
  for (const registration of [
    'commands::chat::save_chat_composer::<tauri::Unknown>,',
    'commands::chat::save_chat_composer::<tauri::Wry, Extra>,',
    'commands::chat::save_chat_composer::<tauri::Wry,',
  ]) {
    const result = check([ordinary, registration])
    assert.equal(result.status, 1)
    assert.match(result.stderr, /missing: save_chat_composer/)
  }
})

test('nested generated response types preserve the command census', () => {
  for (const responseType of ['RecordWriteOutcome<Finding>', '{\nrecord: Finding,\n} | null']) {
    const result = check([ordinary, composer], responseType)
    assert.equal(result.status, 0, result.stderr)
    assert.match(result.stdout, /OK.*2 commands/)
  }
})
