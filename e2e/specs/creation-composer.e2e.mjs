import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { readlinkSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { readClipboardText } from '../fixtures/clipboard-readback.mjs'
import { openCreationAi } from './creation-helpers.mjs'
import { capture, click, clipboardPixels, create, fill, fixture, fixtureStarted, imageFile, native, out, receipt, recordVideo, resize, rows, save, tab } from './composer-proof.mjs'

const requestClose = () => execFileSync('python3', [join(process.cwd(), 'e2e/fixtures/request-native-close.py')], { encoding: 'utf8', timeout: 5_000 })
const draftBody = '[aria-label="Creation draft body"][contenteditable="true"]'
const input = kind => `[aria-label="${kind === 'finding' ? 'Finding' : 'Test case'} title"]`
const list = (kind, sessionId) => native(kind === 'finding' ? 'list_findings' : 'list_drafts', { sessionId })
let session, note, localImage, shared, ordinary, generated, activeRecorder

describe('Unified creation composer in the built native application', () => {
  after(async () => { if (activeRecorder) await activeRecorder.stop() })
  it('opens and saves all four ordinary routes without provider setup or blank records', async () => {
    await $('button=New Session').waitForClickable()
    await click('button=New Session')
    await fill('[aria-label="Session title"]', 'Composer native proof')
    await browser.waitUntil(async () => (await native('list_sessions')).some(session => session.title === 'Composer native proof'))
    session = (await native('list_sessions')).find(session => session.title === 'Composer native proof')
    note = (await native('list_entries', { sessionId: session.id })).find(entry => entry.entryType === 'note')
    const providerLink = join(fixture, 'bin/codex')
    const providerTarget = readlinkSync(providerLink)
    unlinkSync(providerLink)
    await browser.refresh()
    assert.ok((await native('get_provider_status')).providers.every(provider => !provider.available))
    for (const route of ['Note', 'collection']) {
      for (const kind of ['finding', 'testware']) {
        await tab(route === 'Note' ? 'Note' : kind === 'finding' ? 'Findings' : 'Test cases')
        const before = rows()
        await create(kind)
        assert.equal(await $(input(kind)).getValue(), '')
        assert.deepEqual(rows(), before)
        await capture(`uc1-open-${route}-${kind}`)
        await click('button=Cancel')
        assert.deepEqual(rows(), before)
        await create(kind)
        const title = `${route} ${kind} ordinary`
        await fill(input(kind), title)
        await fill(draftBody, 'Visible authored body.')
        if (kind === 'finding') await browser.execute(() => {
          const field = Array.from(document.querySelectorAll('.creation-fields label')).find(label => label.querySelector('span')?.textContent === 'Severity').querySelector('select')
          field.value = 'high'; field.dispatchEvent(new Event('change', { bubbles: true }))
        })
        await browser.execute(label => {
          const button = Array.from(document.querySelectorAll('button')).find(button => button.textContent.trim() === label)
          button.click(); button.click()
        }, kind === 'finding' ? 'Save finding' : 'Save test cases')
        await $(`h2=${title}`).waitForDisplayed()
        const records = await list(kind, session.id)
        assert.equal(records.length, 1)
        assert.equal(records[0].body, '<p>Visible authored body.</p>')
        assert.equal(rows().creation_attempts, before.creation_attempts + 1)
        await click(`[aria-label="Copy ${title}"]`)
        await $(`[aria-label="${title} copied"]`).waitForDisplayed()
        assert.equal(readClipboardText().plain, `## ${title}\n\n${kind === 'finding' ? '**Severity:** High\n\n' : ''}Visible authored body.`)
        await click('button=Edit')
        assert.equal(await $(input(kind)).getValue(), title)
        await click('button=Discard')
        await capture(`uc1-saved-${route}-${kind}`)
        await native(kind === 'finding' ? 'delete_finding' : 'delete_draft', { id: records[0].id })
        await browser.refresh()
      }
    }
    receipt('ordinary-four-entry-points', { rows: rows(), providers: await native('get_provider_status') })
    symlinkSync(providerTarget, providerLink)
    await browser.refresh()
  })
  it('fits the composer in both themes across the approved native CSS widths', async () => {
    for (const theme of ['light', 'dark']) {
      await click('button=Settings')
      await click(`button=${theme === 'light' ? 'Light' : 'Dark'}`)
      await click('button=Back')
      await tab('Findings')
      await create('finding')
      for (const width of [1280, 1024, 768, 360, 320]) {
        const viewport = await resize(width)
        const geometry = await browser.execute(() => ({ width: innerWidth, pageWidth: Math.max(document.body.scrollWidth, document.documentElement.scrollWidth),
          controls: Array.from(document.querySelectorAll('.creation-composer button'), node => { const box = node.getBoundingClientRect(); return { label: node.textContent.trim(), left: box.left, right: box.right } }) }))
        receipt(`layout-${theme}-${width}`, { viewport, geometry })
        assert.ok(geometry.pageWidth <= geometry.width + 1)
        assert.ok(geometry.controls.every(control => control.left >= -1 && control.right <= geometry.width + 1))
        await capture(`uc2-${theme}-${width}`)
      }
      await resize(1280)
      await click('button=Cancel')
    }
  })
  it('retains local and shared images, source review, cancellation and one saved AI result', async () => {
    localImage = await imageFile()
    shared = await native('import_clipboard_screenshot', { sessionId: session.id, entryId: note.id, filename: 'shared-note.png', dataUrl: localImage })
    const sourceBody = `<p>Exact source for the native review.</p><img src="qa-scribe-attachment://${shared.id}" data-attachment-id="${shared.id}" alt="Shared Note screenshot">`
    await native('update_entry', { id: note.id, patch: { body: sourceBody, bodyJson: JSON.stringify({ schemaVersion: 1, doc: { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Exact source for the native review.' }] }, { type: 'image', attrs: { src: `qa-scribe-attachment://${shared.id}`, attachmentId: shared.id, alt: 'Shared Note screenshot' } }] } }), bodyFormat: 'tiptap_json' } })
    await browser.refresh()
    await $('h1=Issues and risks').waitForDisplayed()
    await create('finding')
    const sharedBefore = rows()
    await browser.execute(id => {
      const data = new DataTransfer()
      data.setData('text/html', `<p>Borrowed evidence</p><img src="qa-scribe-attachment://${id}" data-attachment-id="${id}" alt="Shared Note screenshot">`)
      document.querySelector('[aria-label="Creation draft body"]').dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
    }, shared.id)
    await $(`.creation-composer img[data-attachment-id="${shared.id}"]`).waitForExist()
    await capture('uc1-shared-reference')
    await click('button=Cancel')
    await click('button=Discard draft')
    assert.deepEqual(rows(), sharedBefore)
    assert.ok(await native('get_attachment_preview_data_url', { attachmentId: shared.id }))

    await create('finding')
    await fill(input('finding'), 'Borrowed Note image saved')
    await browser.execute(id => {
      const data = new DataTransfer()
      data.setData('text/html', `<p>Borrowed evidence</p><img src="qa-scribe-attachment://${id}" data-attachment-id="${id}" alt="Shared Note screenshot">`)
      document.querySelector('[aria-label="Creation draft body"]').dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
    }, shared.id)
    await $(`.creation-composer img[data-attachment-id="${shared.id}"]`).waitForExist()
    await save('finding')
    const borrowedRecord = (await list('finding', session.id))[0]
    assert.ok(borrowedRecord.body.includes(shared.id))
    assert.equal(rows().attachments, sharedBefore.attachments)
    await click('[aria-label="Copy first Borrowed Note image saved screenshot"]')
    assert.deepEqual(await clipboardPixels(), { width: 1, height: 1, rgba: [255, 0, 0, 255] })
    await capture('uc1-shared-save-and-copy')
    await native('delete_finding', { id: borrowedRecord.id })
    await browser.refresh()
    await $('h1=Issues and risks').waitForDisplayed()
    activeRecorder = recordVideo()
    await create('finding')
    await fill(input('finding'), 'x'.repeat(161))
    await fill(draftBody, 'Retain local screenshots after failed Save.')
    const { stageImage } = await import('./composer-proof.mjs')
    await stageImage(localImage, 'upload')
    await stageImage(localImage, 'paste')
    const beforeCopy = rows()
    await click('.creation-composer button[aria-label^="Copy first"]')
    assert.deepEqual(await clipboardPixels(), { width: 1, height: 1, rgba: [255, 0, 0, 255] })
    assert.deepEqual(rows(), beforeCopy)
    await click('button=Save finding')
    await browser.waitUntil(() => browser.execute(() => document.querySelector('[role="alert"]')?.textContent.includes('160')))
    assert.equal(await $(input('finding')).getValue(), 'x'.repeat(161))
    assert.equal(rows().findings, 0)
    assert.equal(rows().attachments, sharedBefore.attachments)
    await capture('uc1-save-error-retention')
    await fill(input('finding'), 'AAA retained screenshot finding')
    const windows = execFileSync('xdotool', ['search', '--onlyvisible', '--name', 'QA Scribe E2E'], { encoding: 'utf8', timeout: 5_000 }).trim().split(/\s+/)
    assert.equal(windows.length, 1)
    execFileSync('xdotool', ['windowfocus', '--sync', windows[0]], { timeout: 5_000 })
    execFileSync('xdotool', ['key', '--clearmodifiers', 'ctrl+s'], { timeout: 5_000 })
    await $('h2=AAA retained screenshot finding').waitForDisplayed()
    ordinary = (await list('finding', session.id))[0]
    assert.ok(!ordinary.body.includes('data:image/'))
    assert.ok(!ordinary.bodyJson.includes('base64'))
    await browser.waitUntil(() => browser.execute(() => Array.from(document.querySelectorAll('.record-detail-pane img')).every(image => image.complete && image.naturalWidth > 0)))
    await click('[aria-label="Copy first AAA retained screenshot finding screenshot"]')
    assert.deepEqual(await clipboardPixels(), { width: 1, height: 1, rgba: [255, 0, 0, 255] })
    await capture('uc1-local-image-saved-and-copy')
    await create('finding')
    await fill(input('finding'), 'AI draft retained through cancellation')
    await fill(draftBody, 'This authored draft must survive cancellation.')
    await stageImage(localImage, 'paste')
    const authoredBody = await $(draftBody).getText()
    await openCreationAi('finding')
    assert.ok((await $('dialog').getText()).includes('Exact source for the native review.'))
    assert.ok((await $('dialog').getText()).includes('immediately saves one AI result'))
    const beforeSetup = rows()
    await capture('uc2-ai-exact-source')
    await click('dialog button=Cancel')
    assert.deepEqual(rows(), beforeSetup)
    assert.equal(await $(input('finding')).getValue(), 'AI draft retained through cancellation')
    await click('button=Prefill from note')
    const revisedBody = sourceBody.replace('Exact source for the native review.', 'Changed canonical source needs new confirmation.')
    await native('update_entry', { id: note.id, patch: { body: revisedBody, bodyJson: JSON.stringify({ schemaVersion: 1, doc: { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Changed canonical source needs new confirmation.' }] }, { type: 'image', attrs: { src: `qa-scribe-attachment://${shared.id}`, attachmentId: shared.id, alt: 'Shared Note screenshot' } }] } }), bodyFormat: 'tiptap_json' } })
    await click('dialog button=Prefill and replace draft')
    await $('dialog*=Changed canonical source needs new confirmation.').waitForDisplayed()
    assert.equal(await $(draftBody).getText(), authoredBody)
    await capture('uc2-source-revision-refresh')
    await click('dialog button=Keep editing')
    await openCreationAi('finding')
    await click('dialog button=Generate and replace draft')
    await fixtureStarted(1)
    const beforeCancel = rows()
    requestClose()
    await $('dialog*=Generation is still running').waitForDisplayed()
    await capture('uc2-native-close-generation')
    await click('button=Keep waiting')
    requestClose()
    await click('button=Cancel generation')
    await $('dialog*=Save before leaving?').waitForDisplayed()
    await click('button=Keep editing')
    assert.equal(await $(input('finding')).getValue(), 'AI draft retained through cancellation')
    assert.equal(await $(draftBody).getText(), authoredBody)
    assert.equal(rows().findings, beforeCancel.findings)
    await capture('uc2-cancel-restores-local-images')
    await browser.execute(() => { const sort = document.querySelector('.collection-sort select'); sort.value = 'title'; sort.dispatchEvent(new Event('change', { bubbles: true })) })
    await openCreationAi('finding')
    await click('dialog button=Generate and replace draft')
    await fixtureStarted(2)
    writeFileSync(join(fixture, 'codex-exec-2.release'), 'explicit native fixture release\n')
    await browser.waitUntil(async () => {
      const title = await $('.record-detail-pane .record-title')
      return await title.isExisting() && await title.getText() === 'E2E finding' && !await $('.creation-composer').isExisting()
    })
    generated = (await list('finding', session.id)).find(record => record.title === 'E2E finding')
    assert.ok(generated)
    assert.equal(rows().findings, beforeCancel.findings + 1)
    assert.equal(await $('.creation-composer').isExisting(), false)
    assert.equal(await $('.record-master-list button[aria-current="true"] strong').getText(), 'E2E finding')
    await browser.waitUntil(() => browser.execute(() => { const images = Array.from(document.querySelectorAll('.record-detail-pane img')); return images.length > 0 && images.every(image => image.complete && image.naturalWidth > 0) }))
    await click('[aria-label="Copy first E2E finding screenshot"]')
    assert.deepEqual(await clipboardPixels(), { width: 1, height: 1, rgba: [255, 0, 0, 255] })
    await click('[aria-label="Copy E2E finding"]')
    await $('[aria-label="E2E finding copied"]').waitForDisplayed()
    assert.equal(readClipboardText().plain, '## E2E finding\n\n## E2E finding\n\nDeterministic provider output.\n\nImage: Shared Note screenshot')
    await capture('uc2-one-selected-saved-result')
    await activeRecorder.stop()
    activeRecorder = null
  })
  it('settles lost responses and native close, leaving one owned startup-recovery reservation', async () => {
    await create('finding')
    await fill(input('finding'), 'Lost response converges')
    await fill(draftBody, 'Native commit succeeds before a simulated transport response loss.')
    await browser.execute(() => {
      const original = window.__TAURI_INTERNALS__.invoke
      window.__TAURI_INTERNALS__.invoke = async function (command, args, options) {
        if (command !== 'commit_creation_save') return original.call(this, command, args, options)
        window.__TAURI_INTERNALS__.invoke = original
        await original.call(this, command, args, options)
        throw new Error('Probe lost response after actual native commit')
      }
    })
    const beforeLost = rows()
    await save('finding')
    await $('h2=Lost response converges').waitForDisplayed()
    assert.equal(rows().findings, beforeLost.findings + 1)
    assert.equal(rows().creation_attempts, beforeLost.creation_attempts + 1)
    await capture('uc1-lost-response-committed-wins')

    const bytes = Buffer.from(localImage.split(',')[1], 'base64')
    const recovery = await native('prepare_creation_save', { request: { attemptId: 'composer-native-recovery', sessionId: session.id, kind: 'finding', images: [
      { localId: 'recovery-image', filename: 'recovery.png', mimeType: 'image/png', sizeBytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') },
    ] } })
    const seed = { sessionId: session.id, noteId: note.id, sharedId: shared.id, ordinaryId: ordinary.id, generatedId: generated.id, recovery, rows: rows() }
    writeFileSync(join(process.env.QA_SCRIBE_E2E_TEMP_ROOT, 'composer-seed.json'), JSON.stringify(seed, null, 2))
    writeFileSync(join(out, 'restart-seed.json'), JSON.stringify(seed, null, 2))
    await create('finding')
    await fill(input('finding'), 'Native close keeps then discards this draft')
    const beforeClose = rows()
    requestClose(); requestClose()
    await $('dialog*=Save before leaving?').waitForDisplayed()
    assert.equal(await $$('dialog[open]').then(dialogs => dialogs.length), 1)
    await capture('uc1-native-close-dirty-settlement')
    await click('button=Keep editing')
    assert.equal(await $(input('finding')).getValue(), 'Native close keeps then discards this draft')
    requestClose()
    const discard = await $('button=Discard draft')
    await discard.waitForClickable()
    await discard.click()
    await browser.waitUntil(async () => {
      try { await fetch(`${browser.options.protocol}://${browser.options.hostname}:${browser.options.port}/status`, { signal: AbortSignal.timeout(500) }); return false }
      catch (error) { return error.cause?.code === 'ECONNREFUSED' }
    })
    assert.deepEqual(rows(), beforeClose)
    receipt('native-close-discarded-no-row', { before: beforeClose, after: rows(), windowClosed: true })
    browser.overwriteCommand('deleteSession', async () => null)
  })
})
